function facosAplicarIdioma() {
    const idioma = localStorage.getItem('painelIdioma') || 'pt';

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const chave = el.getAttribute('data-i18n');
        const entrada = FACOS_I18N[chave];
        if (entrada && entrada[idioma]) {
            el.textContent = entrada[idioma];
        }
    });

    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
        const chave = el.getAttribute('data-i18n-html');
        const entrada = FACOS_I18N[chave];
        if (entrada && entrada[idioma]) {
            el.innerHTML = entrada[idioma];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        const chave = el.getAttribute('data-i18n-placeholder');
        const entrada = FACOS_I18N[chave];
        if (entrada && entrada[idioma]) {
            el.setAttribute('placeholder', entrada[idioma]);
        }
    });

    document.documentElement.lang = idioma === 'en' ? 'en' : 'pt-BR';
    return idioma;
}

function facosTrocarIdioma() {
    const atual = localStorage.getItem('painelIdioma') || 'pt';
    const novo = atual === 'pt' ? 'en' : 'pt';
    localStorage.setItem('painelIdioma', novo);
    return facosAplicarIdioma();
}

// Helper para textos montados dinamicamente em JS (listas, cards, status,
// mensagens de alerta etc.) — usar em vez de escrever string em português
// direto no meio do código. Ex: traduzirProfissional('pedido.status.pendente')
function traduzirProfissional(chave) {
    const idioma = localStorage.getItem('painelIdioma') || 'pt';
    const entrada = FACOS_I18N[chave];
    if (entrada && entrada[idioma]) return entrada[idioma];
    if (entrada && entrada.pt) return entrada.pt;
    return chave;
}

// Atalho pra checar o idioma atual sem repetir a chave do localStorage
function facosIdiomaAtual() {
    return localStorage.getItem('painelIdioma') || 'pt';
}

window.traduzirProfissional = traduzirProfissional;
window.facosIdiomaAtual = facosIdiomaAtual;

document.addEventListener('DOMContentLoaded', facosAplicarIdioma);
